# frozen_string_literal: true

require "pty"
require "rbconfig"
require "timeout"
require "esphome/cli/monitor"

RSpec.describe ESPHome::Cli::Monitor do
  it "drains the resize events generated by ncurses without creating a feedback loop" do
    script = <<~RUBY
      require "esphome/cli/monitor"
      require "ostruct"

      monitor = ESPHome::Cli::Monitor.new(OpenStruct.new)
      monitor.define_singleton_method(:render_all) {}
      monitor.instance_variable_set(:@sub_active, true)
      begin
        monitor.send(:ensure_screen)
        IO.console.winsize = [30, 100]
        monitor.resize_display
        monitor.win.timeout = 0
        events = 0
        while monitor.win.getch == Curses::KEY_RESIZE
          events += 1
          raise "resize feedback loop" if events > 2

          monitor.resize_display
        end
        raise "terminal did not resize" unless monitor.win.maxy == 30 && monitor.win.maxx == 100
      ensure
        monitor.send(:close_screen)
      end
      puts "resize settled"
    RUBY

    expect(run_in_terminal(script)).to include("resize settled")
  end

  it "shrinks and grows a form while preserving edited text and its cursor beyond the visible field" do
    script = <<~RUBY
      require "esphome/cli/monitor"
      require "ostruct"

      monitor = ESPHome::Cli::Monitor.new(OpenStruct.new)
      monitor.define_singleton_method(:render_all) {}
      monitor.instance_variable_set(:@sub_active, true)
      popup_class = Class.new(ESPHome::Cli::Entity) do
        include ESPHome::Cli::Entities::MenuPrompt
        include ESPHome::Cli::Entities::FormPrompt
        attr_accessor :actions, :widths

        def build_form_dialog(...)
          dialog = super
          widths << dialog[0].width
          popup = self
          dialog[2].define_singleton_method(:getch) do
            action = popup.actions.shift
            raise "ran out of input" unless action

            if action.is_a?(Array)
              IO.console.winsize = action
              popup.cli.instance_variable_set(:@resize_pending, true)
              Curses::KEY_RESIZE
            else
              action
            end
          end
          dialog
        end
      end
      begin
        IO.console.winsize = [24, 40]
        monitor.send(:ensure_screen)
        popup = popup_class.new(monitor, OpenStruct.new(name: "Value"), 0)
        popup.widths = []
        popup.actions = [Curses::KEY_RIGHT, *Array.new(3, Curses::KEY_LEFT), "X",
                         [24, 8], "Y", [24, 20], [24, 100], "Z", 10]
        initial = "abcdefghijklmnopqrstuvwxyz" * 2
        value = popup.send(:prompt_form, "Long form title", initial_value: initial, suffix: nil, field_width: 100)
        expected = initial.dup.insert(49, "XYZ")
        raise "form input or cursor was lost" unless value == expected
        raise "field did not shrink and grow" unless popup.widths == [36, 4, 16, 96]
      ensure
        monitor.send(:close_screen)
      end
      puts "form resized"
    RUBY

    expect(run_in_terminal(script)).to include("form resized")
  end

  it "highlights only the initial text, including internal spaces, before and after resizing" do
    script = <<~RUBY
      require "esphome/cli/monitor"
      require "ostruct"

      monitor = ESPHome::Cli::Monitor.new(OpenStruct.new)
      monitor.define_singleton_method(:render_all) {}
      monitor.instance_variable_set(:@sub_active, true)
      popup_class = Class.new(ESPHome::Cli::Entity) do
        include ESPHome::Cli::Entities::MenuPrompt
        include ESPHome::Cli::Entities::FormPrompt
        attr_accessor :actions, :checks

        def build_form_dialog(...)
          dialog = super
          popup = self
          sub = dialog[3]
          dialog[2].define_singleton_method(:getch) do
            cursor = [sub.cury, sub.curx]
            sub.maxx.times do |column|
              sub.setpos(0, column)
              selected = (sub.inch & Curses::A_REVERSE) != 0
              raise "selection extends past text or misses text" unless selected == (column < 7)
            end
            sub.setpos(*cursor)
            popup.checks += 1
            action = popup.actions.shift
            if action.is_a?(Array)
              IO.console.winsize = action
              popup.cli.instance_variable_set(:@resize_pending, true)
              Curses::KEY_RESIZE
            else
              action
            end
          end
          dialog
        end
      end
      begin
        IO.console.winsize = [24, 40]
        monitor.send(:ensure_screen)
        popup = popup_class.new(monitor, OpenStruct.new(name: "Value"), 0)
        popup.actions = [[24, 8], [24, 80], 10]
        popup.checks = 0
        value = popup.send(:prompt_form, "Value", initial_value: "abc def", suffix: nil, field_width: 100)
        raise "selected text changed" unless value == "abc def" && popup.checks == 3
      ensure
        monitor.send(:close_screen)
      end
      puts "selection fits text"
    RUBY

    expect(run_in_terminal(script)).to include("selection fits text")
  end

  def run_in_terminal(script)
    output = +""
    status = nil
    PTY.spawn({ "TERM" => "xterm" }, RbConfig.ruby, "-Ilib", "-e", script) do |reader, _writer, pid|
      Timeout.timeout(5) do
        begin
          loop { output << reader.readpartial(4096) }
        rescue Errno::EIO, EOFError
          # The slave terminal closes when the child exits.
        end
        _, status = Process.waitpid2(pid)
      end
    end

    expect(status).to be_success, output
    output
  end
end
